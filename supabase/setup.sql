-- PULP MVP database setup
-- Run this in Supabase > SQL Editor after confirming fashion_brands has imported successfully.
-- This keeps your existing public.fashion_brands table and its 305 imported records.

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references public.fashion_brands(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  review_text text not null check (char_length(review_text) between 20 and 5000),
  category_ratings jsonb not null default '{}'::jsonb,
  website_photo_url text,
  received_photo_url text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

create index if not exists reviews_brand_status_created_idx
  on public.reviews (brand_id, status, created_at desc);
create index if not exists reviews_user_created_idx
  on public.reviews (user_id, created_at desc);

alter table public.fashion_brands enable row level security;
alter table public.reviews enable row level security;

-- Public visitors can browse the imported brand directory.
drop policy if exists "Anyone can read fashion brands" on public.fashion_brands;
create policy "Anyone can read fashion brands"
  on public.fashion_brands for select using (true);

-- Public visitors see approved reviews only; signed-in authors can also see their own submissions.
drop policy if exists "Read approved reviews or own submissions" on public.reviews;
create policy "Read approved reviews or own submissions"
  on public.reviews for select
  using (status = 'approved' or auth.uid() = user_id);

-- A signed-in user may submit a review only as themselves. Status remains pending by default.
drop policy if exists "Signed-in users submit their own pending reviews" on public.reviews;
create policy "Signed-in users submit their own pending reviews"
  on public.reviews for insert
  with check (auth.uid() = user_id and status = 'pending');

-- Do not add public UPDATE/DELETE policies. Approve/reject submissions from the Supabase dashboard.
